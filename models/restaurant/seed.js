function buildRestaurantDocs(list) {
  return list.map(
    ([
      name,
      zone,
      rating,
      ratingCount,
      cuisines,
      avgDeliveryTimeMin,
      costForTwo,
      coordinates,
      image,
    ]) => ({
      name,
      zone,
      cuisines,
      rating,
      ratingCount,
      avgDeliveryTimeMin,
      costForTwo,
      address: `${zone}`,
      location: { type: "Point", coordinates },
      open: true,
      image: image || "",
    })
  );
}

