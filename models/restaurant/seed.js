async function seed() {
  await mongoose.connect(MONGO);
  await Restaurant.deleteMany({});
  await MenuItem.deleteMany({});

  const docs = [
    ...buildRestaurantDocs(hydRestaurants),
    ...buildRestaurantDocs(blrRestaurants),
  ];
  const created = await Restaurant.insertMany(docs);

  const menuItems = buildMenuItems(created);
  await MenuItem.insertMany(menuItems);

  console.log(
    `Seed complete: ${created.length} restaurants, ${menuItems.length} menu items`
  );
  await mongoose.disconnect();
  process.exit(0);
}

seed().catch((e) => {
  console.error(e);
  process.exit(1);
});
